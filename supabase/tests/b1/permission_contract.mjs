// Phase B1 helper for the reviewed function-permission contract (scripts/migration-permission-gate.mjs).
//
//   node supabase/tests/b1/permission_contract.mjs <db-container> generate   # writes supabase/permissions/<latest migration>.json
//   node supabase/tests/b1/permission_contract.mjs <db-container> check      # compares the live database to that file
//
// The repository gate only accepts the CI container names, so this reuses the gate's own inventory query and comparison with an
// explicit LOCAL container (same refusal rules as supabase/tests/lib/db_target.sh). `generate` keeps the previous contract's
// ordering and public-RPC allow-list, appends only what is new, and PRINTS every added / changed / removed function so the diff
// against the last reviewed contract is the review artifact: a B1 migration must add ONLY its own functions.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { compare, inventory, root, stable } from "../../../scripts/migration-permission-gate.mjs";

const [container, mode = "check"] = process.argv.slice(2);
if (!container || !/^supabase_db_[A-Za-z0-9_-]+$/.test(container) || /staging|prod/i.test(container) || container === "supabase_db_aladdin") {
  console.error("REFUSED: name an isolated local supabase_db_<project> container");
  process.exit(2);
}
const psql = (sql) => execFileSync("docker", ["exec", "-i", container, "psql", "-X", "-qAt", "-U", "postgres", "-d", "postgres", "-v", "ON_ERROR_STOP=1"], { input: sql, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }).trim();

// PRE-EXISTING base drift, found in Phase B1 and independent of it: on a clean local replay of main (+ #119 + A2, WITHOUT the B1
// migration) these 13 functions already differ from the committed contract 20261026090001 - the live database grants service_role
// EXECUTE where the reviewed contract says none. B1 neither causes nor fixes it, so the generator keeps the reviewed entries
// untouched and the checker reports them separately instead of failing B1 for them (or silently blessing the local values).
const KNOWN_BASE_DRIFT = new Set([
  "public.account_entry_allowed(text)", "public.account_password_confirm(text,text,text)", "public.admin_phone_cooldown_override(text,text)",
  "public.admin_phone_cooldown_status(text)", "public.admin_users_directory(text,text,text,text,text,text,integer,integer)",
  "public.branch_location_set(uuid,text,text,text)", "public.my_secondary_phone()", "public.organization_legal_name_set(uuid,text)",
  "public.secondary_phone_cancel()", "public.secondary_phone_change(text,uuid)", "public.secondary_phone_make_primary(uuid,text,text)",
  "public.secondary_phone_renew()", "public.secondary_phone_reserve(text,uuid)",
]);
const dir = path.join(root, "supabase/permissions");
const versions = fs.readdirSync(dir).filter((f) => /^\d{14}\.json$/.test(f)).map((f) => f.slice(0, 14)).sort();
const latestMigration = fs.readdirSync(path.join(root, "supabase/migrations")).filter((f) => f.endsWith(".sql")).map((f) => f.slice(0, 14)).sort().at(-1);
const live = JSON.parse(psql("BEGIN READ ONLY;" + inventory + "ROLLBACK;"));

if (mode === "generate") {
  const prevVersion = versions.filter((v) => v < latestMigration).at(-1);
  const prev = JSON.parse(fs.readFileSync(path.join(dir, `${prevVersion}.json`), "utf8"));
  const prevBySig = new Map(prev.functions.map((f) => [f.signature, f]));
  const liveBySig = new Map(live.map((f) => [f.signature, f]));
  const added = live.filter((f) => !prevBySig.has(f.signature)).map((f) => f.signature);
  const removed = prev.functions.filter((f) => !liveBySig.has(f.signature)).map((f) => f.signature);
  const changed = live.filter((f) => prevBySig.has(f.signature) && stable(f) !== stable(prevBySig.get(f.signature))).map((f) => f.signature);
  // Reviewed entries are kept exactly as committed (never overwritten with local values); only new functions are appended.
  const ordered = [...prev.functions.filter((f) => liveBySig.has(f.signature)),...live.filter((f) => !prevBySig.has(f.signature)).sort((a, b) => a.signature.localeCompare(b.signature))];
  const out = {
    version: latestMigration,
    source: `local supabase/postgres:17 replay of every migration through this version (isolated stack ${container.replace("supabase_db_", "")}); generated by supabase/tests/b1/permission_contract.mjs`,
    publicRPCs: prev.publicRPCs,
    functions: ordered,
  };
  fs.writeFileSync(path.join(dir, `${latestMigration}.json`), `${JSON.stringify(out, null, 1)}\n`);
  console.log(`previous contract: ${prevVersion} (${prev.functions.length} functions) -> ${latestMigration} (${ordered.length})`);
  console.log(`ADDED   (${added.length}):\n  ${added.join("\n  ") || "-"}`);
  console.log(`DIFFERENT FROM THE REVIEWED CONTRACT BUT NOT WRITTEN (${changed.length}; known base drift: ${changed.filter((x) => KNOWN_BASE_DRIFT.has(x)).length}):\n  ${changed.join("\n  ") || "-"}`);
  const unexpected = changed.filter((x) => !KNOWN_BASE_DRIFT.has(x));
  if (unexpected.length) { console.error(`UNEXPECTED permission change on existing functions: ${unexpected.join(", ")}`); process.exit(1); }
  console.log(`REMOVED (${removed.length}):\n  ${removed.join("\n  ") || "-"}`);
} else if (mode === "check") {
  const file = JSON.parse(fs.readFileSync(path.join(dir, `${latestMigration}.json`), "utf8"));
  const errors = compare(live, file.functions);
  const drift = errors.filter((e) => KNOWN_BASE_DRIFT.has(e.split(": ")[0]));
  const real = errors.filter((e) => !KNOWN_BASE_DRIFT.has(e.split(": ")[0]));
  if (real.length) { console.error(real.join("\n")); process.exit(1); }
  if (drift.length) {
    // Strict by default: the base drift is NOT normalized. It is printed in full every time, and it only lets this check pass when the
    // caller states --accept-known-base-drift (supabase/tests/b1/run_b1.sh does, and says so in its summary). Details and options:
    // docs/security/PHONE_VERIFICATION_B1_BASE_PERMISSION_DRIFT.md
    const sigs = new Set(drift.map((e) => e.split(": ")[0]));
    console.log(`BASE DRIFT (pre-existing, unreviewed, NOT caused or fixed by B1) - ${sigs.size} functions differ from the reviewed contract:\n  ${drift.join("\n  ")}`);
    if (!process.argv.includes("--accept-known-base-drift")) { console.error("FAIL: base drift present and not explicitly accepted (--accept-known-base-drift)"); process.exit(1); }
    console.log(`ACCEPTED-FOR-B1-ONLY: ${sigs.size} functions (explicit flag; this is not a review approval of those permissions)`);
  }
  const anonPublic = file.functions.filter((f) => f.signature.startsWith("public.") && f.effective.anon && !file.publicRPCs.includes(f.signature));
  if (anonPublic.length) { console.error(`Broad anonymous allow-listing: ${anonPublic.map((f) => f.signature).join(", ")}`); process.exit(1); }
  console.log(`PASS ${file.functions.length} exact function permission contracts (${latestMigration})`);
} else {
  console.error("unknown mode");
  process.exit(2);
}
