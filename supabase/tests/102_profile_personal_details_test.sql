-- profile_set_personal_details: self-only write path for birth_date / gender.
create extension if not exists pgtap;
begin;
select no_plan();
select ok(not has_column_privilege('authenticated', 'public.profiles', 'birth_date', 'update'), 'no direct birth_date writes');
select ok(not has_column_privilege('authenticated', 'public.profiles', 'gender', 'update'), 'no direct gender writes');
select ok(not has_function_privilege('anon', 'public.profile_set_personal_details(date,text)', 'execute'), 'anonymous caller cannot set personal details');
update auth.users set email_confirmed_at = now() where id = '70000010-0000-4000-8000-000000000010';
set local role authenticated;
set local request.jwt.claims = '{"sub":"70000010-0000-4000-8000-000000000010","role":"authenticated"}';
select lives_ok($$select public.profile_set_personal_details(date '1990-05-17', 'female')$$, 'caller saves their own details');
select is((select birth_date from public.profiles where user_id = auth.uid()), date '1990-05-17', 'birth date is stored');
select is((select gender from public.profiles where user_id = auth.uid()), 'female', 'gender is stored');
select throws_ok($$select public.profile_set_personal_details(current_date + 1, null)$$, '22023', null, 'future birth date is rejected');
select throws_ok($$select public.profile_set_personal_details(null, 'other')$$, '22023', null, 'unsupported gender is rejected');
select lives_ok($$select public.profile_set_personal_details(null, '')$$, 'both values can be cleared');
select is((select gender from public.profiles where user_id = auth.uid()), null, 'cleared gender is NULL');
set local request.jwt.claims = '{"sub":"70000001-0000-4000-8000-000000000001","role":"authenticated"}';
select is((select count(*)::integer from public.profiles where birth_date is not null), 0, 'another caller sees no birth dates');
reset role;
select * from finish();
rollback;
