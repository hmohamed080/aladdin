-- Reference data about places, not about people: readable, never writable.
revoke all on app.place_governorates, app.place_cities from public, anon, authenticated, service_role;
grant select on app.place_governorates, app.place_cities to authenticated, service_role;

-- No SET search_path on purpose: every name below is schema-qualified, and a function
-- SET clause costs a GUC save/restore on EVERY call, which dominates when a board of
-- thousands of jobs is resolved row by row.
create function app.resolve_governorate(p_text text)
returns text
language sql
stable
as $$
  select g.key
  from app.place_governorates g
  where g.name_norm = (select nullif(app.normalize_place(p_text), ''))
  limit 1;
$$;

comment on function app.resolve_governorate(text) is
  'The catalogue governorate key whose key, Arabic or English name equals p_text after normalisation, or NULL. Backed by app.place_governorates (generated from frontend/src/lib/installer/location-data.ts, parity-tested).';

create function app.resolve_city(p_governorate_key text, p_text text)
returns text
language sql
stable
as $$
  select c.key
  from app.place_cities c
  where c.governorate_key = p_governorate_key
    and c.name_norm = (select nullif(app.normalize_place(p_text), ''))
  limit 1;
$$;

comment on function app.resolve_city(text, text) is
  'The catalogue city key INSIDE the given governorate that p_text names exactly, or NULL. "other" is a catalogue entry like any other. Backed by app.place_cities (generated from frontend/src/lib/installer/location-data.ts, parity-tested).';
