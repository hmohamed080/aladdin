-- ===========================================================================
-- Installer Jobs — the PLACE CATALOGUE (Egypt governorates and cities)
--
-- One reference catalogue of places, generated from
-- `frontend/src/lib/installer/location-data.ts` (a unit test fails if the two ever
-- diverge), so there is one catalogue with two readers rather than two lists.
-- Every later migration that needs "where is this?" asks it HERE: the canonical
-- job location (jobs.governorate_key / city_key), the caller's service areas, the
-- board's governorate / city filters and the Overall Match location component.
--
-- LOCATION IS RESOLVED EXACTLY, NEVER GUESSED. A free-text place resolves to a
-- catalogue place only when its text, after lossless orthographic normalisation
-- (case, whitespace, Arabic diacritics and tatweel), equals one of that place's
-- own catalogue names — exactly what `frontend/src/lib/installer/
-- opportunity-location.ts` does.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- Place resolution (immutable, catalogue-backed)
-- ---------------------------------------------------------------------------
create function app.normalize_place(p_text text)
returns text
language sql
immutable
set search_path = ''
as $$
  -- NFKC, drop Arabic tashkeel (U+064B-U+065F, U+0670) and tatweel (U+0640),
  -- collapse whitespace, trim, lower-case. Mirrors normalizePlace() in the app.
  select lower(btrim(regexp_replace(
           regexp_replace(normalize(coalesce(p_text, ''), nfkc), E'[\u064B-\u065F\u0670\u0640]', '', 'g'),
           E'\\s+', ' ', 'g')));
$$;

comment on function app.normalize_place(text) is
  'Lossless orthographic normalisation of a place name (case, whitespace, Arabic diacritics, tatweel). Mirrors normalizePlace() in frontend/src/lib/installer/opportunity-location.ts.';

-- The catalogue is DATA: two small reference tables generated from
-- `frontend/src/lib/installer/location-data.ts` (a unit test fails if they ever
-- diverge). A name is stored once as written and once normalised (a generated
-- column), so resolving a place is an index probe — not a scan that re-normalises
-- ~400 names per call, which matters when a board of thousands of jobs is
-- resolved row by row.
create table app.place_governorates (
  key       text not null,
  name      text not null,
  name_norm text generated always as (app.normalize_place(name)) stored,
  primary key (key, name)
);
create index ix_place_governorates_norm on app.place_governorates (name_norm);

create table app.place_cities (
  governorate_key text not null,
  key             text not null,
  name            text not null,
  name_norm       text generated always as (app.normalize_place(name)) stored,
  primary key (governorate_key, key, name)
);
create index ix_place_cities_norm on app.place_cities (governorate_key, name_norm);

comment on table app.place_governorates is
  'Egypt governorate catalogue: every key + Arabic + English name. Reference data generated from frontend/src/lib/installer/location-data.ts (parity-tested). Read-only to clients.';
comment on table app.place_cities is
  'Egypt city catalogue, inside its governorate: every key + Arabic + English name. "other" is a catalogue entry like any other. Generated from frontend/src/lib/installer/location-data.ts (parity-tested). Read-only to clients.';

