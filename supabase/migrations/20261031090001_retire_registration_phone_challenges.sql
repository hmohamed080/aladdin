-- R2: retire the registration flow's own WhatsApp-code table.
--
-- Migration 20261028090001 (PR #113) created public.phone_verification_challenges so the sign-up server could store an HMAC of the
-- code it generated itself. Since R2 the sign-up flow uses the ONE phone verification authority (app.phone_verification_challenges
-- and the phone_signup_* functions, migrations 20261030090001/2): the code is generated, MACed, checked and rate-limited there, and
-- the account is created only with the single-use grant that authority returns. Nothing reads or writes this table any more, so it
-- is a second, weaker authority that must not survive.
--
-- Forward-only on purpose: 20261028090001 may already be applied on a hosted project and is NOT edited. That migration keeps
-- adding users.birth_date (still used) and creating this table; this one removes the table. Plain DROP, no CASCADE: if anything
-- unexpected depends on it, the migration fails loudly instead of taking the dependent with it.
--
-- ROLLOUT ORDER (expand / contract): deploy the application that no longer touches the table first, then apply this migration.
-- Rows are one-time code hashes with a lifetime of at most 30 minutes; dropping them only ends a code that was already in flight.
drop table if exists public.phone_verification_challenges;
