-- ===========================================================================
-- Marketplace PR 11 — the signed-in cart, the guest-cart merge and the "no buying from your own showroom" rule
-- ===========================================================================
-- WHAT THIS IS (docs/product/marketplace-implementation-plan-20261121.md, PR 11; walkthrough Part 4C)
--
--   1. marketplace_cart_items       the account cart: one row per (buyer, variant) with a quantity. It stores NO price, NO
--                                   stock figure and NO delivery fee: the cart page quotes every line again through
--                                   marketplace_public_cart, so a number is always the showroom's current one.
--   2. marketplace_cart_merges      a ledger that makes the guest-cart merge happen exactly once per merge key.
--   3. marketplace_cart_get / _merge / _replace / _own_sellers   the only ways in and out of that cart.
--   4. The own-showroom rule        a member of a showroom cannot put that showroom's products in a cart, and cannot place an
--                                   order with it. Enforced by triggers on the cart table AND on marketplace_orders (the checkout
--                                   path, today's marketplace_checkout_place and the checkout v2 of PR 12), so no RPC can bypass it.
--
-- SECURITY
--   * marketplace_cart_items: RLS on, the owner may SELECT her own rows; NO client write grant (writes only through the RPCs
--     below, which are SECURITY DEFINER, authenticated-only and re-check an active account). marketplace_cart_merges: RPC-only.
--   * A line is named by public slug + SKU; the browser never supplies a price. Quantity is a whole number 1..9999 per line and a
--     cart holds at most 50 lines (the same limits as the public quote). A showroom's stock is NOT checked here: checkout
--     reserves it and refuses when it is short.
--   * Adding a NEW line needs the product live (published, enabled showroom, Marketplace open, active variant). Lines that are
--     already in the cart stay when the product later sells out or is withdrawn, so the page can mark them and block checkout.
--   * Closed Marketplace (marketplace_open = false): nothing can be added or merged.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------------
create table public.marketplace_cart_items (
  user_id    uuid        not null references public.users (id) on delete cascade,
  variant_id uuid        not null references public.marketplace_product_variants (id) on delete cascade,
  quantity   integer     not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pk_marketplace_cart_items primary key (user_id, variant_id),
  constraint ck_marketplace_cart_items_quantity check (quantity between 1 and 9999)
);
comment on table public.marketplace_cart_items is
  'The signed-in buyer''s cart: variant + quantity only (never a price, stock or fee). Written only by marketplace_cart_merge / marketplace_cart_replace; read through marketplace_cart_get. A BEFORE trigger refuses a product of a showroom the buyer belongs to.';
create index ix_marketplace_cart_items_variant on public.marketplace_cart_items (variant_id);

create trigger set_marketplace_cart_items_updated_at
  before update on public.marketplace_cart_items
  for each row execute function app.set_updated_at();

alter table public.marketplace_cart_items enable row level security;
revoke all on public.marketplace_cart_items from public, anon, authenticated, service_role;
grant select on public.marketplace_cart_items to authenticated;
create policy marketplace_cart_items_select_owner on public.marketplace_cart_items
  for select to authenticated using (user_id = (select auth.uid()));
-- NO insert / update / delete policy and NO such grant, in any role.

create table public.marketplace_cart_merges (
  user_id       uuid        not null references public.users (id) on delete cascade,
  merge_key     uuid        not null,
  merged_lines  integer     not null default 0,
  skipped_lines integer     not null default 0,
  created_at    timestamptz not null default now(),
  constraint pk_marketplace_cart_merges primary key (user_id, merge_key)
);
comment on table public.marketplace_cart_merges is
  'One row per guest-cart merge (merge key generated by the browser). A second call with the same key changes nothing. Rows older than 90 days are removed by the next merge of the same buyer.';
alter table public.marketplace_cart_merges enable row level security;
revoke all on public.marketplace_cart_merges from public, anon, authenticated, service_role;
-- RLS on and no policy and no grant: invisible to every client role.

-- ---------------------------------------------------------------------------
-- 2. Internal helpers
-- ---------------------------------------------------------------------------
-- Is the user an active member of the showroom? (Any role: whoever works for a showroom is on the selling side of it.)
create or replace function app.marketplace_user_belongs_to_seller(p_user_id uuid, p_org_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.memberships m
    where m.user_id = p_user_id and m.organization_id = p_org_id and m.status = 'active');
$$;

-- The variant behind a slug + SKU whatever its state (null when no such product / variant exists).
create or replace function app.marketplace_cart_variant_any(p_slug text, p_sku text)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select pv.id
  from public.marketplace_products p
  join public.marketplace_product_variants pv on pv.product_id = p.id
  where p_slug ~ '^[a-z0-9-]{1,120}$' and p.slug = p_slug
    and p_sku ~ '^[A-Za-z0-9][A-Za-z0-9._/-]{0,63}$' and pv.sku = p_sku;
$$;

-- Is the variant on sale right now (the same predicate the public quote and the checkout use, plus the Marketplace switch)?
create or replace function app.marketplace_cart_variant_is_live(p_variant_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.marketplace_product_variants pv
    join public.marketplace_products p on p.id = pv.product_id
    where pv.id = p_variant_id and pv.status = 'active' and p.status = 'published'
      and app.marketplace_seller_is_public(p.seller_organization_id)
      and exists (select 1 from public.marketplace_product_types pt
                  join public.marketplace_categories pc on pc.id = pt.category_id
                  where pt.id = p.product_type_id and pt.is_active and pc.is_active));
$$;

-- The rule, in one place: a cart row or an order of a buyer who belongs to the selling showroom is refused.
create or replace function app.marketplace_refuse_own_showroom()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_org uuid;
begin
  if tg_table_name = 'marketplace_cart_items' then
    select pv.seller_organization_id into v_org from public.marketplace_product_variants pv where pv.id = new.variant_id;
    if app.marketplace_user_belongs_to_seller(new.user_id, v_org) then
      raise exception 'mp:own_showroom' using errcode = '23514';
    end if;
  else
    if app.marketplace_user_belongs_to_seller(new.buyer_user_id, new.seller_organization_id) then
      raise exception 'mp:own_showroom' using errcode = '23514';
    end if;
  end if;
  return new;
end;
$$;

create trigger trg_marketplace_cart_items_own_showroom
  before insert or update of variant_id, user_id on public.marketplace_cart_items
  for each row execute function app.marketplace_refuse_own_showroom();
create trigger trg_marketplace_orders_own_showroom
  before insert on public.marketplace_orders
  for each row execute function app.marketplace_refuse_own_showroom();

-- Reads and validates one { slug, sku, qty } element; returns the variant and the quantity or raises.
create or replace function app.marketplace_cart_parse_line(p_line jsonb, p_index integer, out v_variant uuid, out v_qty integer)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_raw text;
begin
  if jsonb_typeof(p_line) <> 'object' then
    raise exception 'mp:invalid_line:%', p_index using errcode = '22023';
  end if;
  v_raw := p_line ->> 'qty';
  if v_raw is null or v_raw !~ '^[0-9]{1,4}$' or v_raw::integer not between 1 and 9999 then
    raise exception 'mp:invalid_quantity:%', p_index using errcode = '22023';
  end if;
  v_qty := v_raw::integer;
  v_variant := app.marketplace_cart_variant_any(btrim(p_line ->> 'slug'), btrim(p_line ->> 'sku'));
end;
$$;

revoke all on function
  app.marketplace_user_belongs_to_seller(uuid, uuid),
  app.marketplace_cart_variant_any(text, text),
  app.marketplace_cart_variant_is_live(uuid),
  app.marketplace_refuse_own_showroom(),
  app.marketplace_cart_parse_line(jsonb, integer)
  from public, anon, authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 3. The buyer-facing RPCs (authenticated only)
-- ---------------------------------------------------------------------------
-- The account cart as references: { open, lines: [ { slug, sku, qty } ] }. Prices come from marketplace_public_cart.
-- A line of a showroom the buyer belongs to is never returned.
create or replace function public.marketplace_cart_get()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
begin
  if v_uid is null then
    raise exception 'mp:auth_required' using errcode = '42501';
  end if;
  if not app.account_is_active(v_uid) then
    raise exception 'mp:account_inactive' using errcode = '42501';
  end if;
  return jsonb_build_object(
    'open', app.marketplace_is_open(),
    'lines', coalesce((
      select jsonb_agg(jsonb_build_object('slug', p.slug, 'sku', pv.sku, 'qty', c.quantity) order by c.created_at, pv.sku)
      from public.marketplace_cart_items c
      join public.marketplace_product_variants pv on pv.id = c.variant_id
      join public.marketplace_products p on p.id = pv.product_id
      where c.user_id = v_uid and not app.marketplace_user_belongs_to_seller(v_uid, pv.seller_organization_id)), '[]'::jsonb));
end;
$$;

-- Merges the guest cart into the account cart, exactly once per p_merge_key (a second call with the same key returns the cart
-- as it is and changes nothing). Quantities add up, capped at 9999 per line; lines past 50 are skipped. A guest line is skipped
-- when its product is not on sale, does not exist, or belongs to a showroom the buyer works for.
-- p_lines: [ { "slug", "sku", "qty" } ]  (at most 50). Nothing in it is a price.
-- Returns { replayed, merged, skipped, own_showroom (count), ...the cart (marketplace_cart_get) }.
create or replace function public.marketplace_cart_merge(p_merge_key uuid, p_lines jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid     uuid := (select auth.uid());
  e         jsonb;
  i         integer := 0;
  p         record;
  v_variant uuid;
  v_qty     integer;
  v_merged  integer := 0;
  v_skipped integer := 0;
  v_own     integer := 0;
  v_count   integer;
  v_done    integer;
begin
  if v_uid is null then
    raise exception 'mp:auth_required' using errcode = '42501';
  end if;
  if not app.account_is_active(v_uid) then
    raise exception 'mp:account_inactive' using errcode = '42501';
  end if;
  if p_merge_key is null or p_lines is null or jsonb_typeof(p_lines) <> 'array' then
    raise exception 'mp:invalid_lines' using errcode = '22023';
  end if;
  if jsonb_array_length(p_lines) > 50 then
    raise exception 'mp:too_many_lines' using errcode = '22023';
  end if;
  if not app.marketplace_is_open() then
    raise exception 'mp:marketplace_closed' using errcode = '23514';
  end if;

  -- exactly once: the first caller with this key claims it, any other (a retry, a second tab) finds it taken
  insert into public.marketplace_cart_merges (user_id, merge_key) values (v_uid, p_merge_key)
    on conflict (user_id, merge_key) do nothing;
  get diagnostics v_done = row_count;
  if v_done = 0 then
    return jsonb_build_object('replayed', true, 'merged', 0, 'skipped', 0, 'own_showroom', 0) || public.marketplace_cart_get();
  end if;
  delete from public.marketplace_cart_merges where user_id = v_uid and created_at < now() - interval '90 days';

  -- a line of the same variant twice in the guest cart is added once with the sum
  for p in
    select x.variant, least(sum(x.qty), 9999)::integer as qty, min(x.ord) as ord
    from (
      select t.ord, (app.marketplace_cart_parse_line(t.x, t.ord::integer)).v_variant as variant,
             (app.marketplace_cart_parse_line(t.x, t.ord::integer)).v_qty as qty
      from jsonb_array_elements(p_lines) with ordinality as t(x, ord)) x
    group by x.variant
    order by min(x.ord)
  loop
    v_variant := p.variant;
    v_qty := p.qty;
    if v_variant is null then
      v_skipped := v_skipped + 1;
      continue;
    end if;
    if app.marketplace_user_belongs_to_seller(v_uid, (select pv.seller_organization_id from public.marketplace_product_variants pv where pv.id = v_variant)) then
      v_own := v_own + 1;
      v_skipped := v_skipped + 1;
      continue;
    end if;
    if exists (select 1 from public.marketplace_cart_items c where c.user_id = v_uid and c.variant_id = v_variant) then
      update public.marketplace_cart_items c set quantity = least(c.quantity + v_qty, 9999)
       where c.user_id = v_uid and c.variant_id = v_variant;
      v_merged := v_merged + 1;
      continue;
    end if;
    if not app.marketplace_cart_variant_is_live(v_variant) then
      v_skipped := v_skipped + 1;
      continue;
    end if;
    select count(*) into v_count from public.marketplace_cart_items c where c.user_id = v_uid;
    if v_count >= 50 then
      v_skipped := v_skipped + 1;
      continue;
    end if;
    insert into public.marketplace_cart_items (user_id, variant_id, quantity) values (v_uid, v_variant, v_qty);
    v_merged := v_merged + 1;
  end loop;

  update public.marketplace_cart_merges set merged_lines = v_merged, skipped_lines = v_skipped
   where user_id = v_uid and merge_key = p_merge_key;
  return jsonb_build_object('replayed', false, 'merged', v_merged, 'skipped', v_skipped, 'own_showroom', v_own)
         || public.marketplace_cart_get();
end;
$$;

-- Makes the account cart equal to p_lines (the browser mirror of the signed-in cart). A line already in the cart keeps its place
-- (its product may have sold out meanwhile; the page marks it). A NEW line must be on sale. A line of a showroom the buyer works for
-- is REFUSED for the whole call ('mp:own_showroom'), nothing changes. Lines that are not listed are removed.
-- p_lines: [ { "slug", "sku", "qty" } ]  (at most 50; the empty array empties the cart).
create or replace function public.marketplace_cart_replace(p_lines jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid     uuid := (select auth.uid());
  p         record;
  v_keep    uuid[] := '{}';
  v_org     uuid;
  v_exists  boolean;
begin
  if v_uid is null then
    raise exception 'mp:auth_required' using errcode = '42501';
  end if;
  if not app.account_is_active(v_uid) then
    raise exception 'mp:account_inactive' using errcode = '42501';
  end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' then
    raise exception 'mp:invalid_lines' using errcode = '22023';
  end if;
  if jsonb_array_length(p_lines) > 50 then
    raise exception 'mp:too_many_lines' using errcode = '22023';
  end if;

  for p in
    select x.variant, x.qty, x.ord
    from (
      select t.ord, (app.marketplace_cart_parse_line(t.x, t.ord::integer)).v_variant as variant,
             (app.marketplace_cart_parse_line(t.x, t.ord::integer)).v_qty as qty
      from jsonb_array_elements(p_lines) with ordinality as t(x, ord)) x
    order by x.ord
  loop
    if p.variant is null then
      continue;  -- no such product / SKU: nothing to keep
    end if;
    if p.variant = any (v_keep) then
      raise exception 'mp:duplicate_line' using errcode = '22023';
    end if;
    select pv.seller_organization_id into v_org from public.marketplace_product_variants pv where pv.id = p.variant;
    if app.marketplace_user_belongs_to_seller(v_uid, v_org) then
      raise exception 'mp:own_showroom' using errcode = '23514';
    end if;
    select exists (select 1 from public.marketplace_cart_items c where c.user_id = v_uid and c.variant_id = p.variant) into v_exists;
    if not v_exists and not app.marketplace_cart_variant_is_live(p.variant) then
      continue;  -- a dead product cannot be put into a cart
    end if;
    v_keep := array_append(v_keep, p.variant);
  end loop;

  -- second pass: apply (the first pass has refused everything that could fail)
  delete from public.marketplace_cart_items c where c.user_id = v_uid and c.variant_id <> all (v_keep);
  for p in
    select (app.marketplace_cart_parse_line(t.x, t.ord::integer)).v_variant as variant,
           (app.marketplace_cart_parse_line(t.x, t.ord::integer)).v_qty as qty
    from jsonb_array_elements(p_lines) with ordinality as t(x, ord)
    order by t.ord
  loop
    continue when p.variant is null or p.variant <> all (v_keep);
    insert into public.marketplace_cart_items (user_id, variant_id, quantity) values (v_uid, p.variant, p.qty)
      on conflict (user_id, variant_id) do update set quantity = excluded.quantity;
  end loop;
  return public.marketplace_cart_get();
end;
$$;

-- The public slugs of the showrooms the signed-in buyer works for, so the page can hide "add to cart" on their own products.
create or replace function public.marketplace_cart_own_sellers()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
begin
  if v_uid is null then
    raise exception 'mp:auth_required' using errcode = '42501';
  end if;
  return coalesce((
    select jsonb_agg(o.slug order by o.slug)
    from public.memberships m
    join public.organizations o on o.id = m.organization_id
    where m.user_id = v_uid and m.status = 'active' and o.slug is not null
      and exists (select 1 from public.marketplace_seller_accounts a where a.organization_id = o.id)), '[]'::jsonb);
end;
$$;

